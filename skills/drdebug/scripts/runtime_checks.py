#!/usr/bin/env python3
"""Runtime preflight and opt-in startup configuration for the public adapter.

This file never imports a user task or a model provider. Metadata checks run in
child interpreters; a small NPU numerical probe requires ``runtime_probe=True``.
No drivers, packages, accounts or global Python startup files are modified.
"""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import stat
import subprocess
import sys
import sysconfig

MARKER = "DRDEBUG_RUNTIME_JSON="
MODE_VARIABLE = "DRDEBUG_DETERMINISM"
CONFIG_VARIABLE = "DRDEBUG_RUNTIME_STARTUP_CONFIG"
RECEIPT_VARIABLE = "DRDEBUG_RUNTIME_RECEIPTS"
CONFIG_HASH_VARIABLE = "DRDEBUG_RUNTIME_STARTUP_CONFIG_SHA256"


class RuntimeConfigurationError(ValueError):
    pass


# Python normally prints and ignores errors from sitecustomize. This hook must
# terminate instead: continuing would silently change the numerical contract.
# It is generated into the workspace adapter, never the paper source or venv.
STARTUP_HOOK = r'''"""DRDebug managed runtime startup; generated by the public adapter."""
import hashlib as _dr_h
import json as _dr_j
import os as _dr_o
from pathlib import Path as _dr_P
import stat as _dr_s
import sys as _dr_sys
import time as _dr_t

if _dr_o.environ.get("DRDEBUG_RUNTIME_STARTUP_CONFIG"):
    _dr_record = {"schema_version": 1, "pid": _dr_o.getpid(), "ppid": _dr_o.getppid(),
                  "time_ns": _dr_t.time_ns(), "python": _dr_sys.executable,
                  "python_version": _dr_sys.version.split()[0], "prefix": _dr_sys.prefix,
                  "status": "startup_failed", "deterministic_enabled": None, "warn_only": None}
    try:
        _dr_config_path = _dr_P(_dr_o.environ["DRDEBUG_RUNTIME_STARTUP_CONFIG"])
        if _dr_config_path.is_symlink() or not _dr_config_path.is_file():
            raise RuntimeError("startup_contract_missing_or_linked")
        _dr_raw = _dr_config_path.read_bytes()
        if _dr_h.sha256(_dr_raw).hexdigest() != _dr_o.environ.get("DRDEBUG_RUNTIME_STARTUP_CONFIG_SHA256"):
            raise RuntimeError("startup_contract_hash_mismatch")
        _dr_config = _dr_j.loads(_dr_raw)
        _dr_mode = _dr_o.environ.get("DRDEBUG_DETERMINISM")
        if _dr_config.get("schema_version") != 1 or _dr_mode not in ("on", "off") or _dr_config.get("mode") != _dr_mode:
            raise RuntimeError("startup_contract_mode_mismatch")
        _dr_hook_sha = _dr_h.sha256(_dr_P(__file__).read_bytes()).hexdigest()
        if _dr_hook_sha != _dr_config.get("hook_sha256"):
            raise RuntimeError("startup_hook_hash_mismatch")
        _dr_receipts = _dr_P(_dr_o.environ["DRDEBUG_RUNTIME_RECEIPTS"])
        if _dr_receipts.is_symlink() or not _dr_receipts.is_dir():
            raise RuntimeError("startup_receipt_directory_unavailable")
        import torch as _dr_torch
        import torch_npu as _dr_npu
        _dr_torch.use_deterministic_algorithms(_dr_mode == "on", warn_only=False)
        _dr_enabled = bool(_dr_torch.are_deterministic_algorithms_enabled())
        _dr_warn = bool(_dr_torch.is_deterministic_algorithms_warn_only_enabled())
        if _dr_enabled != (_dr_mode == "on") or _dr_warn:
            raise RuntimeError("startup_flags_not_applied")
        _dr_record.update(status="configured_before_user_entrypoint", mode=_dr_mode,
                          deterministic_enabled=_dr_enabled, warn_only=_dr_warn,
                          torch=str(_dr_torch.__version__), torch_npu=str(_dr_npu.__version__),
                          hook_sha256=_dr_hook_sha,
                          config_sha256=_dr_h.sha256(_dr_raw).hexdigest())
        _dr_target = _dr_receipts / (str(_dr_record["time_ns"]) + "-" + str(_dr_record["pid"]) + ".json")
        _dr_fd = _dr_o.open(str(_dr_target), _dr_o.O_WRONLY | _dr_o.O_CREAT | _dr_o.O_EXCL, 0o600)
        with _dr_o.fdopen(_dr_fd, "w", encoding="utf-8") as _dr_f:
            _dr_j.dump(_dr_record, _dr_f, sort_keys=True)
            _dr_f.write("\n")
        _dr_sys._drdebug_runtime_startup = dict(_dr_record, receipt_path=str(_dr_target))
    except BaseException as _dr_exc:
        # Exception text can include external paths or package diagnostics. Keep
        # the terminal diagnostic deliberately bounded and credential-free.
        try:
            _dr_o.write(2, ("DRDebug runtime startup failed (" + type(_dr_exc).__name__ +
                            "); refusing interpreter continuation, exit 78.\n").encode())
        finally:
            _dr_o._exit(78)
'''


def _encode(value):
    return (json.dumps(value, indent=2, sort_keys=True) + "\n").encode("utf-8")


def _mode(mode):
    if mode not in {"on", "off"}:
        raise RuntimeConfigurationError("determinism must be on or off")
    return mode


def _regular(path):
    try:
        return stat.S_ISREG(path.lstat().st_mode) and not path.is_symlink()
    except OSError:
        return False


def _check_directory(path):
    path = Path(path).absolute()
    if any(parent.is_symlink() for parent in (path, *path.parents)):
        raise RuntimeConfigurationError("Runtime adapter/receipt paths must not traverse symlinks")
    if path.exists() and not path.is_dir():
        raise RuntimeConfigurationError("Runtime adapter/receipt path is not a directory")
    return path


def startup_contract(mode):
    return {"schema_version": 1, "mode": _mode(mode),
            "hook_sha256": hashlib.sha256(STARTUP_HOOK.encode("utf-8")).hexdigest(),
            "scope": "Before Python user entrypoints that retain site/PYTHONPATH; no cross-version/device or all-operation guarantee."}


def configure_runtime_environment(base_env, directory, mode, receipt_directory=None):
    """Stage fixed adapter files once and return ``(environment, contract)``.

    Repeated calls only validate identical bytes. Receipts live outside this
    immutable directory and are not part of its source inventory.
    """
    directory = _check_directory(directory)
    receipts = _check_directory(receipt_directory or directory.parent / "adapter-receipts")
    if receipts == directory or directory in receipts.parents:
        raise RuntimeConfigurationError("Startup receipts must be outside the adapter source tree")
    contract = startup_contract(mode)
    expected = {"sitecustomize.py": STARTUP_HOOK.encode("utf-8"), "startup.json": _encode(contract)}
    directory.mkdir(parents=True, exist_ok=True)
    for name, content in expected.items():
        path = directory / name
        if path.exists() or path.is_symlink():
            if not _regular(path) or path.read_bytes() != content:
                raise RuntimeConfigurationError("Existing runtime adapter differs; prepare a new workspace")
        else:
            with path.open("xb") as handle:
                handle.write(content)
    receipts.mkdir(parents=True, exist_ok=True)
    env = execution_environment(base_env, directory, mode, receipts)
    return env, {**contract, "directory": str(directory), "receipt_directory": str(receipts),
                 "config_sha256": hashlib.sha256(_encode(contract)).hexdigest()}


def execution_environment(base_env, directory, mode, receipt_directory):
    """Read-only adapter validation and child environment construction."""
    directory, receipts = _check_directory(directory), _check_directory(receipt_directory)
    if receipts == directory or directory in receipts.parents:
        raise RuntimeConfigurationError("Startup receipts must be outside the adapter source tree")
    contract = startup_contract(mode)
    if not directory.is_dir() or {path.name for path in directory.iterdir()} != {"sitecustomize.py", "startup.json"}:
        raise RuntimeConfigurationError("Runtime startup adapter must contain exactly sitecustomize.py and startup.json (no cached bytecode)")
    for name, content in (("sitecustomize.py", STARTUP_HOOK.encode("utf-8")), ("startup.json", _encode(contract))):
        path = directory / name
        if not _regular(path) or path.read_bytes() != content:
            raise RuntimeConfigurationError("Missing or changed runtime startup adapter; prepare a new workspace")
    if not receipts.is_dir():
        raise RuntimeConfigurationError("Startup receipt directory is missing")
    loaded = sys.modules.get("sitecustomize")
    existing_hook = getattr(loaded, "__file__", None) if loaded is not None else None
    env = dict(base_env)
    if existing_hook and not isinstance(getattr(sys, "_drdebug_runtime_startup", None), dict):
        # Source-only preparation is allowed on non-NPU workstations, including
        # Homebrew Python's standard sitecustomize. Preserve the conflict for
        # doctor/run instead of hiding it behind the newly configured hook.
        env["DRDEBUG_RUNTIME_SHADOWED_STARTUP"] = str(existing_hook)
    env["PYTHONPATH"] = os.pathsep.join(filter(None, (str(directory), env.get("PYTHONPATH", ""))))
    # Preserve the lexical venv bin path. Resolving its python symlink would
    # accidentally select the base interpreter for the frozen CMake subprocess.
    env["PATH"] = os.pathsep.join(filter(None, (str(Path(sys.executable).absolute().parent), env.get("PATH", ""))))
    env.update({MODE_VARIABLE: mode, CONFIG_VARIABLE: str(directory / "startup.json"),
                CONFIG_HASH_VARIABLE: hashlib.sha256(_encode(contract)).hexdigest(),
                RECEIPT_VARIABLE: str(receipts), "PYTHONDONTWRITEBYTECODE": "1"})
    return env


def startup_evidence(mode=None, env=None):
    """Validate actual early-startup evidence inside an already started child.

    This reads the existing receipt and current flags. It never applies or
    changes the deterministic setting. Missing evidence is an error, including
    interpreters started with ``-S``/``-I`` that bypass the managed hook.
    """
    environment = os.environ if env is None else env
    selected = _mode(mode or environment.get(MODE_VARIABLE))
    config_path = Path(environment.get(CONFIG_VARIABLE, ""))
    directory = _check_directory(config_path.parent)
    receipts = _check_directory(environment.get(RECEIPT_VARIABLE, ""))
    # This validates the fixed adapter bytes and configuration without writing.
    execution_environment(environment, directory, selected, receipts)
    expected_config_sha = hashlib.sha256(_encode(startup_contract(selected))).hexdigest()
    if environment.get(CONFIG_HASH_VARIABLE) != expected_config_sha:
        raise RuntimeConfigurationError("Startup contract environment hash differs")
    record = getattr(sys, "_drdebug_runtime_startup", None)
    if not isinstance(record, dict) or record.get("pid") != os.getpid():
        raise RuntimeConfigurationError("Managed runtime startup receipt is missing for this process")
    receipt_path = Path(record.get("receipt_path", ""))
    if receipt_path.parent != receipts or not _regular(receipt_path):
        raise RuntimeConfigurationError("Startup receipt path is outside the configured receipt directory")
    try:
        stored = json.loads(receipt_path.read_bytes())
    except (OSError, ValueError) as exc:
        raise RuntimeConfigurationError("Startup receipt is unreadable") from exc
    expected_record = {key: value for key, value in record.items() if key != "receipt_path"}
    if stored != expected_record or stored.get("status") != "configured_before_user_entrypoint":
        raise RuntimeConfigurationError("Startup receipt content differs from in-process evidence")
    if (stored.get("mode") != selected or stored.get("deterministic_enabled") is not (selected == "on")
            or stored.get("warn_only") is not False or stored.get("config_sha256") != expected_config_sha
            or stored.get("hook_sha256") != startup_contract(selected)["hook_sha256"]
            or stored.get("python") != sys.executable or stored.get("prefix") != sys.prefix):
        raise RuntimeConfigurationError("Startup process identity/mode/hash differs")
    import torch
    import torch_npu
    if (bool(torch.are_deterministic_algorithms_enabled()) != (selected == "on")
            or torch.is_deterministic_algorithms_warn_only_enabled()
            or str(torch.__version__) != stored.get("torch")
            or str(torch_npu.__version__) != stored.get("torch_npu")):
        raise RuntimeConfigurationError("Current runtime versions or deterministic flags changed after startup")
    return {**record, "receipt_sha256": hashlib.sha256(receipt_path.read_bytes()).hexdigest(),
            "verified_current_flags": True}


