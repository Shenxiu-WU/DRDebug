def _json_probe(command, *, env, timeout):
    try:
        proc = subprocess.run(command, env=env, stdin=subprocess.DEVNULL, capture_output=True,
                              text=True, timeout=timeout, check=False)
    except (OSError, subprocess.TimeoutExpired) as exc:
        return {"ok": False, "error_type": type(exc).__name__}
    matches = [line[len(MARKER):] for line in proc.stdout.splitlines() if line.startswith(MARKER)]
    if proc.returncode != 0 or len(matches) != 1:
        return {"ok": False, "returncode": proc.returncode, "error": "Child probe failed or did not return exactly one structured receipt"}
    try:
        value = json.loads(matches[0])
    except ValueError:
        return {"ok": False, "returncode": proc.returncode, "error": "Invalid child probe JSON"}
    if not isinstance(value, dict):
        return {"ok": False, "returncode": proc.returncode, "error": "Invalid child probe object"}
    return {"ok": True, "returncode": proc.returncode, "data": value}


def _version(binary, *, env, timeout):
    if not binary:
        return {"ok": False, "error": "not found on PATH"}
    try:
        proc = subprocess.run([binary, "--version"], env=env, stdin=subprocess.DEVNULL, capture_output=True,
                              text=True, timeout=timeout, check=False)
        # A version's first line is enough. Do not retain arbitrary CLI dumps.
        first = (proc.stdout or proc.stderr).splitlines()
        return {"ok": proc.returncode == 0, "path": binary, "version": first[0][:240] if first else "", "returncode": proc.returncode}
    except (OSError, subprocess.TimeoutExpired) as exc:
        return {"ok": False, "path": binary, "error_type": type(exc).__name__}


def _toolchain(env):
    selected = env.get("ASCEND_INSTALL_PATH") or env.get("ASCEND_HOME_PATH")
    home = Path.home() / "Ascend/ascend-toolkit/latest"
    return Path(selected or (str(home) if home.is_dir() else "/usr/local/Ascend/ascend-toolkit/latest")).expanduser()


def dependency_report(*, npu=None, soc=None, deterministic="on", runtime_probe=False, timeout_sec=60, env=None):
    """Return structured real-runtime checks without executing any user code.

    ``ready`` means these bounded prerequisites passed, not that the host vendor
    supports an arbitrary version tuple or that a user kernel will pass.
    """
    mode = _mode(deterministic)
    if not isinstance(timeout_sec, (int, float)) or isinstance(timeout_sec, bool) or not 1 <= timeout_sec <= 1800:
        raise RuntimeConfigurationError("Runtime probe timeout must be between 1 and 1800 seconds")
    child_env = dict(os.environ if env is None else env)
    child_env["PYTHONDONTWRITEBYTECODE"] = "1"
    if npu is not None:
        child_env.update(ASCEND_RT_VISIBLE_DEVICES=str(npu), ASCEND_DEVICE_ID="0")
    checks = []

    def add(name, ok, detail, hint=None):
        value = {"name": name, "ok": bool(ok), "detail": detail}
        if hint:
            value["hint"] = hint
        checks.append(value)

    add("python_version", sys.version_info >= (3, 10), sys.version.split()[0], "Use Python 3.10+ in the same isolated environment for every command.")
    path_python = shutil.which("python3", path=child_env.get("PATH"))
    identity = _json_probe([path_python, "-B", "-c", PYTHON_IDENTITY], env=child_env, timeout=timeout_sec) if path_python else {"ok": False, "error": "python3 not found on PATH"}
    expected = {"executable": sys.executable, "prefix": sys.prefix, "base_prefix": sys.base_prefix,
                "version": list(sys.version_info[:3]), "soabi": sysconfig.get_config_var("SOABI")}
    actual = identity.get("data", {})
    same = bool(identity["ok"] and Path(actual.get("prefix", "")).resolve() == Path(sys.prefix).resolve()
                and actual.get("version") == expected["version"] and actual.get("soabi") == expected["soabi"]
                and Path(actual.get("executable", "")).resolve() == Path(sys.executable).resolve())
    add("python_path_identity", same, {"launcher": expected, "path_python3": identity}, "Activate one venv and invoke its python3; the frozen CMake build also invokes python3 from PATH.")
    cmake = _version(shutil.which("cmake", path=child_env.get("PATH")), env=child_env, timeout=timeout_sec)
    match = re.search(r"(?:version\s+)?(\d+)\.(\d+)", cmake.get("version", ""))
    add("cmake", cmake["ok"] and bool(match) and tuple(map(int, match.groups())) >= (3, 16), cmake, "The frozen build requires CMake >= 3.16.")
    compiler = _version(shutil.which("c++", path=child_env.get("PATH")), env=child_env, timeout=timeout_sec)
    add("cxx_compiler", compiler["ok"], compiler, "Install the host C++ toolchain outside DRDebug, then source the toolkit environment.")
    toolkit = _toolchain(child_env)
    add("cann_toolchain", toolkit.is_dir(), str(toolkit), "Source the installed CANN set_env.sh; no toolkit version is guessed or installed automatically.")
    cmake_candidates = [toolkit / part / "ascendc.cmake" for part in
                        ("tools/tikcpp/ascendc_kernel_cmake", "compiler/tikcpp/ascendc_kernel_cmake", "ascendc_devkit/tikcpp/samples/cmake")]
    add("ascendc_cmake", any(path.is_file() for path in cmake_candidates), [str(path) for path in cmake_candidates])
    ccec_candidates = [toolkit / part for part in ("compiler/ccec_compiler/bin/ccec", "compiler/bin/ccec", "bin/ccec")]
    ccec = next((str(path) for path in ccec_candidates if path.is_file() and os.access(path, os.X_OK)), None)
    ccec = ccec or shutil.which("ccec", path=child_env.get("PATH"))
    add("ascendc_compiler", bool(ccec), ccec or [str(path) for path in ccec_candidates], "Install the matching AscendC compiler component; a host C++ compiler alone is insufficient.")
    headers = [toolkit / part for part in ("include/ascendc/basic_api/kernel_operator.h", "tools/tikcpp/tikcfw/kernel_operator.h", "compiler/tikcpp/tikcfw/kernel_operator.h", "include/ascendc/kernel_operator.h")]
    add("ascendc_headers", any(path.is_file() for path in headers), [str(path) for path in headers])
    version_candidates = [toolkit / "version.info", toolkit / "compiler/version.info", *sorted(toolkit.glob("*/ascend_toolkit_install.info"))]
    versions = []
    for path in version_candidates:
        if path.is_file():
            text = path.read_text(encoding="utf-8", errors="replace")[:8192]
            lines = [line[:240] for line in text.splitlines() if re.match(r"(?i)^\s*(?:version|version_dir|cann_version)\s*[:=]", line)]
            versions.append({"path": str(path), "versions": lines})
    add("cann_version_inventory", bool(versions), versions, "Inspect the actual toolkit installation/version files and the vendor's compatibility table; imported Torch alone does not establish compatibility.")
    actual_soc = soc or child_env.get("ASCENDC_SOC_VERSION")
    add("soc", bool(actual_soc), actual_soc or "not selected", "Use --soc with the hardware's real ASCENDC_SOC_VERSION; no B/C default is guessed.")
    metadata = _json_probe([sys.executable, "-B", "-c", RUNTIME_METADATA], env=child_env, timeout=timeout_sec)
    add("runtime_import_probe", metadata["ok"], metadata if not metadata["ok"] else "Isolated package import/version probe completed")
    data = metadata.get("data", {})
    for module in ("numpy", "torch", "torch_npu"):
        report = data.get("imports", {}).get(module, {"ok": False, "error": "runtime metadata probe unavailable"})
        add("python:" + module, report.get("ok"), report, "Install a mutually compatible vendor-supported Python package set in an isolated environment, not globally.")
    package_versions = {name: data.get("imports", {}).get(name, {}).get("version", "") for name in ("torch", "torch_npu")}
    version_pairs = [re.match(r"^(\d+)\.(\d+)(?:\.|$)", package_versions[name]) for name in ("torch", "torch_npu")]
